import pysmartkit

# 1. Adding two numbers
print("1. Addition:", pysmartkit.add(10, 20))

# 2. Square of a number
print("2. Square:", pysmartkit.square(5))

# 3. Check whether a number is even
print("3. Is Even:", pysmartkit.is_even(8))

# 4. Factorial of a number
print("4. Factorial:", pysmartkit.factorial(5))

# 5. Subtract two numbers
print("5. Subtraction:", pysmartkit.subtract(20, 8))

# 6. Multiply two numbers
print("6. Multiplication:", pysmartkit.multiply(6, 4))

# 7. Divide two numbers
print("7. Division:", pysmartkit.divide(20, 4))

# 8. Find the largest of three numbers
print("8. Largest Number:", pysmartkit.largest(10, 25, 15))

# 9. Check whether a number is prime
print("9. Is Prime:", pysmartkit.is_prime(7))

# 10. Convert Celsius to Fahrenheit
print("10. Fahrenheit:", pysmartkit.celsius_to_fahrenheit(100))

# 11. Cube of a number
print("11. Cube:", pysmartkit.cube(3))

# 12. Reverse a string
print("12. Reversed String:", pysmartkit.reverse_string("Python"))
